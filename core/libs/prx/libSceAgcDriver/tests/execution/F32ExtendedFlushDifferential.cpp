int main() {
    try {
        std::setvbuf(stdout, nullptr, _IONBF, 0);
        const auto device = OpenVulkanTestDevice();
        if (!device) return VulkanTestSkipped;
        const bool reportOnly = std::getenv("NPS5_DIFF_REPORT_ONLY") != nullptr;
        std::uint32_t bad = 0;
        struct Mode { const char* name; std::optional<ShaderRecompiler::ShaderFloatMode> mode; };
        const std::array<Mode, 3> modes{{{"no float mode", std::nullopt}, {"IEEE=0 f32 flushed", ShaderRecompiler::ShaderFloatMode{0xc0u, true, false, false}}, {"IEEE=1 all flushed", ShaderRecompiler::ShaderFloatMode{0x00u, false, true, false}}}};
        for (const auto& mode : modes) {
            const auto software = RunAll(*device, false, mode.mode);
            // NPS5_DIFF_CONTROL=1: negative control, the "hardware" side keeps f32 denormals (float mode 0x30), so the table must show DIFFs.
            const auto hardware = std::getenv("NPS5_DIFF_CONTROL") != nullptr ? RunAll(*device, false, ShaderRecompiler::ShaderFloatMode{0x30u, true, false, false}) : RunAll(*device, true, mode.mode);
            std::printf("== %s\n", mode.name);
            for (std::uint32_t op = 0; op < Results; ++op) {
                std::uint32_t mismatches = 0, shown = 0;
                for (std::size_t lane = 0; lane < software.size() / Results; ++lane) {
                    const auto s = software[lane * Results + op], h = hardware[lane * Results + op];
                    if (s == h || (IsNan(s) && IsNan(h))) continue;
                    ++mismatches;
                    if (shown++ < 3) {
                        const std::uint32_t pair = static_cast<std::uint32_t>(lane);
                        std::printf("    %s a=%08x b=%08x: software %08x hardware %08x\n", Names[op], Values[pair / 16u % 16u], Values[pair % 16u], s, h);
                    }
                }
                std::printf("  %-34s %s (%u mismatches)\n", Names[op], mismatches == 0 ? "same" : "DIFF", mismatches);
                bad += mismatches != 0;
            }
        }
        std::printf("ops with mismatches: %u\n", bad);
        return bad != 0 && !reportOnly ? 1 : 0;
    } catch (const std::exception& error) {
        std::cerr << error.what() << '\n';
        return 1;
    }
}
